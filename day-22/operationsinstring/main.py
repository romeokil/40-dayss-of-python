# 2. Relations Operator -> ==,>=,<=,!=

# Yha pe lexicographyically way me socho tb pata chalega

print('hello'=='world')

print('hello'!='world')

print('Goa' == 'Kolkata')

print('Goa' < 'Kolkata')

