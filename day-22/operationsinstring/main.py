# 3. Logical Operations

# Ye thoda sa ajib hai ye bola hai ki Python empty strings ko empty bolta hai and non - empty strings ko True bolta hai

print("" or "hello")

print("" and "hello")

print("hello" and "world")

print("hello" or "world")


# 4. Loops in String

